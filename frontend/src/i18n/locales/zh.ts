/**
 * 翻译条目结构：key 树与 zh 完全一致，值放宽为 string，
 * 供 en/ja/ko 语言包复用（否则字面量类型会导致非 zh 语言无法通过类型检查）。
 */
export type Translation = { [K in keyof typeof zh]: Widen<typeof zh[K]> };
type Widen<T> = T extends string ? string : { [K in keyof T]: Widen<T[K]> };
